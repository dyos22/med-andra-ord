// scripts/update-curated-in-generated.mjs
//
// Lättvikts-regenerering: uppdaterar ENDAST de curated-temana (personer, meningar,
// musik) i words.generated.js från data/curated/{sv,en}.json — utan att ladda ner
// SALDO/Flex/SCOWL. Använd detta när bara curated-innehåll ändrats och lexikon-cachen
// (.cache/wordlists) saknas. För full regenerering av alla teman: scripts/generate-wordlists.mjs.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'words.generated.js');
const CURATED_DIR = path.join(ROOT, 'data', 'curated');

const CURATED_THEMES = ['personer', 'meningar', 'musik'];
const DIFFS = ['easy', 'medium', 'hard', 'barn'];

// ladda nuvarande genererade ordlistor (sätter globalThis.MAO_*)
await import(pathToFileURL(OUT).href);
const words = globalThis.MAO_GENERATED_WORDS;
const meta = globalThis.MAO_WORDLIST_META;
if (!words?.sv || !meta?.counts) throw new Error('Kunde inte läsa words.generated.js');

for (const lang of ['sv', 'en']) {
  const curated = JSON.parse(fs.readFileSync(path.join(CURATED_DIR, `${lang}.json`), 'utf8'));
  for (const theme of CURATED_THEMES) {
    if (!curated[theme]) throw new Error(`Saknar ${lang}.${theme} i curated`);
    words[lang][theme] ||= {};
    meta.counts[lang][theme] ||= {};
    for (const diff of DIFFS) {
      const list = curated[theme][diff]; // verbatim — bevarar skiftläge (t.ex. personnamn), som generatorn
      if (!Array.isArray(list) || !list.length) throw new Error(`Tom/ogiltig curated-lista: ${lang}.${theme}.${diff}`);
      words[lang][theme][diff] = list;
      meta.counts[lang][theme][diff] = list.length;
    }
  }
}

// --- Tilläggs-overlay: extra-words.json läggs OVANPÅ befintliga teman (för lexikon-teman som djur/mat/...) ---
const EXTRA = path.join(CURATED_DIR, 'extra-words.json');
if (fs.existsSync(EXTRA)) {
  const extra = JSON.parse(fs.readFileSync(EXTRA, 'utf8'));
  for (const lang of ['sv', 'en']) {
    for (const [theme, diffs] of Object.entries(extra[lang] || {})) {
      words[lang][theme] ||= {};
      meta.counts[lang][theme] ||= {};
      for (const [diff, list] of Object.entries(diffs)) {
        const base = words[lang][theme][diff] || [];
        const seen = new Set(base.map((w) => (lang === 'sv' ? w.toLocaleLowerCase('sv-SE') : w.toLowerCase())));
        for (const w of list) {
          const n = lang === 'sv' ? w.toLocaleLowerCase('sv-SE') : w.toLowerCase();
          if (n && !seen.has(n)) { seen.add(n); base.push(w); }
        }
        words[lang][theme][diff] = base;
        meta.counts[lang][theme][diff] = base.length;
      }
    }
  }
  console.log('Tilläggs-overlay (extra-words.json) sammanfogad.');
}

meta.note = 'Curated-teman + tilläggs-overlay senast uppdaterade via update-curated-in-generated.mjs';

const body = [
  '/* Generated by scripts/generate-wordlists.mjs. Do not edit by hand. */',
  `globalThis.MAO_WORDLIST_META = ${JSON.stringify(meta, null, 2)};`,
  `globalThis.MAO_GENERATED_WORDS = ${JSON.stringify(words, null, 2)};`,
  '',
].join('\n');
fs.writeFileSync(OUT, body);

console.log('words.generated.js uppdaterad (curated-teman).');
for (const lang of ['sv', 'en']) {
  for (const t of CURATED_THEMES) {
    console.log(`  ${lang}.${t}: ` + DIFFS.map((d) => `${d}=${words[lang][t][d].length}`).join('  '));
  }
}
